import Foundation

/// One typed payload of a pasteboard item, e.g. `public.rtf` → RTF bytes.
public struct PasteboardRepresentation: Sendable, Hashable {
    public var type: String
    public var data: Data

    public init(type: String, data: Data) {
        self.type = type
        self.data = data
    }
}

/// All representations of a single pasteboard item, in the order the source app offered them
/// (richest first, by convention).
public struct PasteboardItemSnapshot: Sendable, Hashable {
    public var representations: [PasteboardRepresentation]

    public init(representations: [PasteboardRepresentation]) {
        self.representations = representations
    }

    public var types: [String] { representations.map(\.type) }

    public func data(for type: String) -> Data? {
        representations.first { $0.type == type }?.data
    }

    public func data(forAnyOf types: [String]) -> (type: String, data: Data)? {
        for type in types {
            if let data = data(for: type) { return (type, data) }
        }
        return nil
    }
}

/// A faithful, Sendable copy of the general pasteboard's contents at one point in time.
public struct PasteboardSnapshot: Sendable, Hashable {
    public var items: [PasteboardItemSnapshot]

    public init(items: [PasteboardItemSnapshot]) {
        self.items = items
    }

    public var isEmpty: Bool { items.allSatisfy { $0.representations.isEmpty } }

    public var byteSize: Int {
        items.reduce(0) { total, item in
            total + item.representations.reduce(0) { $0 + $1.data.count }
        }
    }

    /// Every distinct type across all items.
    public var allTypes: Set<String> {
        Set(items.flatMap(\.types))
    }

    /// The best plain-text rendition of the snapshot, if any.
    public var plainText: String? {
        let strings = items.compactMap { item -> String? in
            if let data = item.data(for: PasteboardType.string), let string = String(data: data, encoding: .utf8) {
                return string
            }
            if let data = item.data(for: PasteboardType.fileURL),
               let string = String(data: data, encoding: .utf8),
               let url = URL(string: string) {
                return url.isFileURL ? url.path : url.absoluteString
            }
            if let data = item.data(for: PasteboardType.url), let string = String(data: data, encoding: .utf8) {
                return string
            }
            return nil
        }
        guard !strings.isEmpty else { return nil }
        return strings.joined(separator: "\n")
    }

    /// File URLs across all items.
    public var fileURLs: [URL] {
        items.compactMap { item in
            guard let data = item.data(for: PasteboardType.fileURL),
                  let string = String(data: data, encoding: .utf8),
                  let url = URL(string: string), url.isFileURL else { return nil }
            return url
        }
    }

    /// A copy containing only plain text — used for "Paste as Plain Text".
    public func plainTextOnly() -> PasteboardSnapshot? {
        guard let text = plainText ?? items.first.flatMap(ContentAnalyzer.derivedText) else { return nil }
        return PasteboardSnapshot(items: [
            PasteboardItemSnapshot(representations: [
                PasteboardRepresentation(type: PasteboardType.string, data: Data(text.utf8)),
            ]),
        ])
    }
}

/// Uniform type identifiers Pasty cares about. Plain strings keep the core free of AppKit types
/// in its model layer and make persistence trivial.
public enum PasteboardType {
    public static let string = "public.utf8-plain-text"
    public static let rtf = "public.rtf"
    public static let rtfd = "com.apple.flat-rtfd"
    public static let html = "public.html"
    public static let url = "public.url"
    public static let urlName = "public.url-name"
    public static let fileURL = "public.file-url"
    public static let png = "public.png"
    public static let tiff = "public.tiff"
    public static let jpeg = "public.jpeg"
    public static let heic = "public.heic"
    public static let gif = "com.compuserve.gif"
    public static let pdf = "com.adobe.pdf"

    /// Image types, most preferred first.
    public static let images = [png, tiff, jpeg, heic, gif]
    public static let richText = [rtfd, rtf, html]

    // MARK: Privacy markers (http://nspasteboard.org)

    /// Content that must never be stored, e.g. passwords from a password manager.
    public static let concealed = "org.nspasteboard.ConcealedType"
    /// Content that only lives on the pasteboard briefly, e.g. an app's internal round-trip.
    public static let transient = "org.nspasteboard.TransientType"
    /// Content generated by an app without explicit user intent.
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    /// The bundle identifier of the app that wrote the content, if it chose to tell us.
    public static let source = "org.nspasteboard.source"

    /// Vendor-specific markers that predate the nspasteboard.org conventions.
    public static let legacySensitiveMarkers: Set<String> = [
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    /// Legacy and UTF-16 translations that the pasteboard synthesizes on demand from the modern
    /// types. Reading them forces synchronous conversion (and, off the main thread, a warning),
    /// and they are regenerated automatically when the modern types are written back.
    public static let synthesized: Set<String> = [
        "public.utf16-external-plain-text", "public.utf16-plain-text", "com.apple.traditional-mac-plain-text",
        "NSStringPboardType", "NeXT plain ascii pasteboard type", "Apple URL pasteboard type",
        "NSFilenamesPboardType", "Apple PNG pasteboard type", "NeXT TIFF v4.0 pasteboard type",
        "NeXT Rich Text Format v1.0 pasteboard type", "NeXT RTFD pasteboard type", "Apple HTML pasteboard type",
        "Apple PDF pasteboard type", "CorePasteboardFlavorType 0x75726C20", "CorePasteboardFlavorType 0x75726C6E",
    ]

    /// Types that describe file promises or other data that cannot be meaningfully replayed.
    public static let unreplayable: Set<String> = [
        "com.apple.NSFilePromiseItemMetaData",
        "com.apple.pasteboard.promised-file-content-type",
        "com.apple.pasteboard.promised-file-url",
        "com.apple.pasteboard.promised-suggested-file-name",
    ]
}
