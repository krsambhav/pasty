import Foundation

/// The rules the clipboard monitor applies before anything is read or stored.
public struct CaptureRules: Sendable, Equatable {
    public var isPaused: Bool
    public var captureImages: Bool
    public var excludedBundleIDs: Set<String>
    /// Skip text that heuristically looks like a password, token or key.
    public var skipLikelySecrets: Bool
    /// Entries larger than this (in bytes, across all representations) are trimmed or skipped.
    public var maxEntryBytes: Int

    public init(
        isPaused: Bool = false,
        captureImages: Bool = true,
        excludedBundleIDs: Set<String> = [],
        skipLikelySecrets: Bool = false,
        maxEntryBytes: Int = 64 * 1_024 * 1_024
    ) {
        self.isPaused = isPaused
        self.captureImages = captureImages
        self.excludedBundleIDs = excludedBundleIDs
        self.skipLikelySecrets = skipLikelySecrets
        self.maxEntryBytes = maxEntryBytes
    }
}

/// Why a clipboard change was not recorded.
public enum SkipReason: Sendable, Equatable {
    case paused
    case markedSensitive
    case excludedApp(String)
    case imagesDisabled
    case likelySecret
    case empty
    case tooLarge
}

public enum PrivacyPolicy {
    /// Decides from pasteboard *types and source alone* — before any data is read.
    public static func evaluate(types: Set<String>, source: SourceApp?, rules: CaptureRules) -> SkipReason? {
        if rules.isPaused { return .paused }
        if types.isEmpty { return .empty }
        if isMarkedSensitive(types) { return .markedSensitive }
        if let bundleID = source?.bundleID, rules.excludedBundleIDs.contains(bundleID) {
            return .excludedApp(bundleID)
        }
        if !rules.captureImages, isImageOnly(types) { return .imagesDisabled }
        return nil
    }

    /// Content explicitly marked by a cooperating app as concealed, transient or auto-generated.
    public static func isMarkedSensitive(_ types: Set<String>) -> Bool {
        types.contains(PasteboardType.concealed)
            || types.contains(PasteboardType.transient)
            || types.contains(PasteboardType.autoGenerated)
            || !types.isDisjoint(with: PasteboardType.legacySensitiveMarkers)
    }

    static func isImageOnly(_ types: Set<String>) -> Bool {
        let hasImage = PasteboardType.images.contains { types.contains($0) }
        let hasText = types.contains(PasteboardType.string) || types.contains(PasteboardType.fileURL)
        return hasImage && !hasText
    }
}

/// A deliberately conservative heuristic for secrets. It cannot catch every password and makes no
/// such promise — it exists to reduce, not eliminate, accidental capture.
public enum SecretDetector {
    private static let knownPrefixes = [
        "sk-", "sk_live_", "sk_test_", "rk_live_", "pk_live_", "ghp_", "gho_", "ghu_", "ghs_", "ghr_",
        "github_pat_", "glpat-", "xoxb-", "xoxp-", "xoxa-", "AKIA", "ASIA", "AIza", "ya29.", "npm_",
        "pypi-", "shpat_", "SG.", "-----BEGIN",
    ]

    public static func looksLikeSecret(_ text: String) -> Bool {
        let candidate = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if candidate.hasPrefix("-----BEGIN"), candidate.contains("PRIVATE KEY") { return true }
        guard candidate.count >= 8, candidate.count <= 256,
              !candidate.contains(where: { $0.isWhitespace }) else { return false }
        if knownPrefixes.contains(where: { candidate.hasPrefix($0) }) && candidate.count >= 16 {
            return true
        }
        // URLs, paths and e-mail addresses are not passwords.
        if candidate.contains("://") || candidate.hasPrefix("/") || candidate.hasPrefix("~") { return false }
        if candidate.contains("@"), candidate.contains("."), candidate.firstIndex(of: "@") != candidate.startIndex {
            return false
        }
        var lower = false, upper = false, digit = false, symbol = false
        for scalar in candidate.unicodeScalars {
            switch scalar {
            case "a"..."z": lower = true
            case "A"..."Z": upper = true
            case "0"..."9": digit = true
            default: symbol = true
            }
        }
        let classes = [lower, upper, digit, symbol].filter { $0 }.count
        // Long random-looking tokens, or short strings mixing every character class.
        if candidate.count >= 32 { return upper && lower && digit && entropyPerCharacter(candidate) > 3.5 }
        return classes == 4 && candidate.count <= 64
    }

    static func entropyPerCharacter(_ string: String) -> Double {
        var counts: [Character: Int] = [:]
        for character in string { counts[character, default: 0] += 1 }
        let length = Double(string.count)
        return counts.values.reduce(0) { total, count in
            let p = Double(count) / length
            return total - p * log2(p)
        }
    }
}

/// Apps that are excluded by default because they routinely handle secrets.
public enum DefaultExclusions {
    public static let apps: [ExcludedApp] = [
        ExcludedApp(bundleID: "com.apple.keychainaccess", name: "Keychain Access"),
        ExcludedApp(bundleID: "com.apple.Passwords", name: "Passwords"),
        ExcludedApp(bundleID: "com.1password.1password", name: "1Password"),
        ExcludedApp(bundleID: "com.agilebits.onepassword7", name: "1Password 7"),
        ExcludedApp(bundleID: "com.bitwarden.desktop", name: "Bitwarden"),
        ExcludedApp(bundleID: "in.sinew.Enpass-Desktop", name: "Enpass"),
        ExcludedApp(bundleID: "com.lastpass.LastPass", name: "LastPass"),
        ExcludedApp(bundleID: "org.keepassxc.keepassxc", name: "KeePassXC"),
    ]
}

public struct ExcludedApp: Sendable, Hashable, Codable, Identifiable {
    public var bundleID: String
    public var name: String
    public var id: String { bundleID }

    public init(bundleID: String, name: String) {
        self.bundleID = bundleID
        self.name = name
    }
}
