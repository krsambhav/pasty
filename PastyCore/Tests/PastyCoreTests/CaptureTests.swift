import AppKit
import XCTest
@testable import PastyCore

/// Exercises real `NSPasteboard` instances (uniquely named, so the user's clipboard is untouched).
final class CaptureTests: XCTestCase {
    private var pasteboard: NSPasteboard!

    override func setUp() {
        super.setUp()
        pasteboard = NSPasteboard(name: NSPasteboard.Name("app.pasty.tests.\(UUID().uuidString)"))
    }

    override func tearDown() {
        pasteboard.releaseGlobally()
        pasteboard = nil
        super.tearDown()
    }

    private func makeMonitor(rules: CaptureRules = CaptureRules(), source: SourceApp? = SourceApp(bundleID: "com.example.editor", name: "Editor")) -> ClipboardMonitor {
        ClipboardMonitor(
            pasteboard: pasteboard,
            rules: rules,
            ownBundleID: "app.pasty.tests",
            sourceProvider: { _ in source },
            handler: { _ in }
        )
    }

    private func copy(_ string: String, extraTypes: [String] = []) {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(string, forType: .string)
        for type in extraTypes {
            item.setData(Data(), forType: NSPasteboard.PasteboardType(type))
        }
        pasteboard.writeObjects([item])
    }

    private func captured(_ result: ClipboardMonitor.PollResult, file: StaticString = #filePath, line: UInt = #line) -> ClipDraft? {
        if case let .captured(draft) = result { return draft }
        XCTFail("Expected a capture, got \(result)", file: file, line: line)
        return nil
    }

    // MARK: Change detection

    func testIgnoresContentPresentAtLaunch() {
        copy("already there")
        let monitor = makeMonitor()
        guard case .unchanged = monitor.pollSynchronously() else { return XCTFail("should not capture pre-existing content") }
    }

    func testDetectsChangeExactlyOnce() {
        let monitor = makeMonitor()
        copy("hello")
        let draft = captured(monitor.pollSynchronously())
        XCTAssertEqual(draft?.title, "hello")
        XCTAssertEqual(draft?.source?.name, "Editor")
        guard case .unchanged = monitor.pollSynchronously() else { return XCTFail("repeated polling must not re-capture") }
    }

    func testRapidConsecutiveCopiesYieldLatest() {
        let monitor = makeMonitor()
        for index in 0..<50 { copy("rapid \(index)") }
        XCTAssertEqual(captured(monitor.pollSynchronously())?.title, "rapid 49")
    }

    func testOwnWritesAreNotRecorded() {
        let monitor = makeMonitor()
        let snapshot = PasteboardSnapshot(items: [
            PasteboardItemSnapshot(representations: [PasteboardRepresentation(type: PasteboardType.string, data: Data("from pasty".utf8))]),
        ])
        monitor.write(snapshot)
        guard case .unchanged = monitor.pollSynchronously() else { return XCTFail("own write recorded") }
        XCTAssertEqual(pasteboard.string(forType: .string), "from pasty")
    }

    func testChangesWhilePausedAreForgottenOnResume() {
        let monitor = makeMonitor(rules: CaptureRules(isPaused: true))
        copy("secret while paused")
        guard case .skipped(.paused) = monitor.pollSynchronously() else { return XCTFail("expected paused") }
        monitor.updateRules(CaptureRules(isPaused: false))
        guard case .unchanged = monitor.pollSynchronously() else { return XCTFail("paused copy leaked after resume") }
        copy("after resume")
        XCTAssertEqual(captured(monitor.pollSynchronously())?.title, "after resume")
    }

    // MARK: Privacy

    func testConcealedAndTransientContentIsNeverStored() {
        let monitor = makeMonitor()
        for marker in [PasteboardType.concealed, PasteboardType.transient, PasteboardType.autoGenerated, "com.agilebits.onepassword"] {
            copy("hunter2", extraTypes: [marker])
            guard case .skipped(.markedSensitive) = monitor.pollSynchronously() else {
                return XCTFail("\(marker) content was not skipped")
            }
        }
    }

    func testExcludedApplicationsAreSkipped() {
        let monitor = makeMonitor(
            rules: CaptureRules(excludedBundleIDs: ["com.example.vault"]),
            source: SourceApp(bundleID: "com.example.vault", name: "Vault")
        )
        copy("from vault")
        guard case .skipped(.excludedApp("com.example.vault")) = monitor.pollSynchronously() else {
            return XCTFail("excluded app captured")
        }
    }

    func testDeclaredSourceIsPassedToProvider() {
        let box = LockedBox<String?>(nil)
        let monitor = ClipboardMonitor(
            pasteboard: pasteboard,
            rules: CaptureRules(),
            ownBundleID: "app.pasty.tests",
            sourceProvider: { declared in
                box.value = declared
                return SourceApp(bundleID: declared, name: nil)
            },
            handler: { _ in }
        )
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString("text", forType: .string)
        item.setString("com.example.declared", forType: NSPasteboard.PasteboardType(PasteboardType.source))
        pasteboard.writeObjects([item])
        XCTAssertEqual(captured(monitor.pollSynchronously())?.source?.bundleID, "com.example.declared")
        XCTAssertEqual(box.value, "com.example.declared")
    }

    func testLikelySecretsSkippedOnlyWhenEnabled() {
        let token = "ghp_aB3dE5fG7hI9jK1lM3nO5pQ7rS9tU1vW3xY5"
        let lenient = makeMonitor()
        copy(token)
        XCTAssertNotNil(captured(lenient.pollSynchronously()))

        let strict = makeMonitor(rules: CaptureRules(skipLikelySecrets: true))
        copy(token)
        guard case .skipped(.likelySecret) = strict.pollSynchronously() else { return XCTFail("secret captured") }
    }

    func testImagesDisabledSkipsImageOnlyContent() throws {
        let monitor = makeMonitor(rules: CaptureRules(captureImages: false))
        pasteboard.clearContents()
        pasteboard.setData(try TestImages.png(width: 40, height: 20), forType: .png)
        guard case .skipped(.imagesDisabled) = monitor.pollSynchronously() else { return XCTFail("image captured") }
    }

    // MARK: Content types & round trips

    func testRichTextIsPreservedThroughRoundTrip() throws {
        let monitor = makeMonitor()
        let attributed = NSAttributedString(string: "Bold move", attributes: [.font: NSFont.boldSystemFont(ofSize: 14)])
        let rtf = try attributed.data(from: NSRange(location: 0, length: attributed.length), documentAttributes: [.documentType: NSAttributedString.DocumentType.rtf])
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setData(rtf, forType: .rtf)
        item.setString("Bold move", forType: .string)
        pasteboard.writeObjects([item])

        let draft = try XCTUnwrap(captured(monitor.pollSynchronously()))
        XCTAssertEqual(draft.kind, .richText)

        let target = NSPasteboard(name: NSPasteboard.Name("app.pasty.tests.target.\(UUID().uuidString)"))
        defer { target.releaseGlobally() }
        PasteboardIO.write(draft.snapshot, to: target)
        XCTAssertEqual(target.data(forType: .rtf), rtf)
        XCTAssertEqual(target.string(forType: .string), "Bold move")
        let restored = try XCTUnwrap(NSAttributedString(rtf: XCTUnwrap(target.data(forType: .rtf)), documentAttributes: nil))
        let font = restored.attribute(.font, at: 0, effectiveRange: nil) as? NSFont
        XCTAssertTrue(font?.fontDescriptor.symbolicTraits.contains(.bold) ?? false)
    }

    func testImagesAreCapturedWithThumbnailAndDimensions() throws {
        let monitor = makeMonitor()
        let png = try TestImages.png(width: 1_600, height: 900)
        pasteboard.clearContents()
        pasteboard.setData(png, forType: .png)

        let draft = try XCTUnwrap(captured(monitor.pollSynchronously()))
        XCTAssertEqual(draft.kind, .image)
        XCTAssertEqual(draft.imageWidth, 1_600)
        XCTAssertEqual(draft.imageHeight, 900)
        let thumbnail = try XCTUnwrap(draft.thumbnail)
        let size = try XCTUnwrap(ImageTools.pixelSize(of: thumbnail))
        XCTAssertLessThanOrEqual(max(size.width, size.height), ContentAnalyzer.thumbnailPixelSize)
        XCTAssertEqual(draft.snapshot.items[0].data(for: PasteboardType.png), png)
    }

    func testLargeScreenshotIsCaptured() throws {
        let monitor = makeMonitor()
        let png = try TestImages.png(width: 5_120, height: 2_880)
        pasteboard.clearContents()
        pasteboard.setData(png, forType: .png)
        let start = Date()
        let draft = try XCTUnwrap(captured(monitor.pollSynchronously()))
        print("[benchmark] 5K screenshot capture+thumbnail: \(Int(Date().timeIntervalSince(start) * 1_000)) ms, \(png.count / 1_024) KB")
        XCTAssertEqual(draft.imageWidth, 5_120)
        XCTAssertNotNil(draft.thumbnail)
    }

    func testMultipleFilesArePreserved() throws {
        let monitor = makeMonitor()
        let urls = [URL(fileURLWithPath: "/tmp/a.txt"), URL(fileURLWithPath: "/tmp/b.png")]
        pasteboard.clearContents()
        pasteboard.writeObjects(urls as [NSURL])

        let draft = try XCTUnwrap(captured(monitor.pollSynchronously()))
        XCTAssertEqual(draft.kind, .file)
        XCTAssertEqual(draft.fileCount, 2)
        XCTAssertEqual(draft.title, "a.txt and 1 more")
        XCTAssertEqual(draft.snapshot.fileURLs.map(\.path), ["/tmp/a.txt", "/tmp/b.png"])

        let target = NSPasteboard(name: NSPasteboard.Name("app.pasty.tests.files.\(UUID().uuidString)"))
        defer { target.releaseGlobally() }
        PasteboardIO.write(draft.snapshot, to: target)
        let restored = target.readObjects(forClasses: [NSURL.self]) as? [URL]
        XCTAssertEqual(restored?.map(\.path), ["/tmp/a.txt", "/tmp/b.png"])
    }

    func testOversizedRepresentationsAreDroppedButEssentialsKept() {
        let monitor = makeMonitor(rules: CaptureRules(maxEntryBytes: 1_024))
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setData(Data(count: 10_000), forType: NSPasteboard.PasteboardType("com.example.huge"))
        item.setString("small text", forType: .string)
        pasteboard.writeObjects([item])

        let draft = captured(monitor.pollSynchronously())
        XCTAssertEqual(draft?.snapshot.allTypes, [PasteboardType.string])
    }

    func testPlainTextOnlyStripsFormatting() {
        let snapshot = PasteboardSnapshot(items: [
            PasteboardItemSnapshot(representations: [
                PasteboardRepresentation(type: PasteboardType.rtf, data: Data("{\\rtf1 x}".utf8)),
                PasteboardRepresentation(type: PasteboardType.string, data: Data("x".utf8)),
            ]),
        ])
        let plain = snapshot.plainTextOnly()
        XCTAssertEqual(plain?.allTypes, [PasteboardType.string])
        XCTAssertEqual(plain?.plainText, "x")
    }
}

/// Minimal thread-safe box for observing values set from `@Sendable` closures.
final class LockedBox<Value>: @unchecked Sendable {
    private let lock = NSLock()
    private var _value: Value
    init(_ value: Value) { _value = value }
    var value: Value {
        get { lock.withLock { _value } }
        set { lock.withLock { _value = newValue } }
    }
}

enum TestImages {
    /// A gradient PNG of the given size, generated without AppKit drawing.
    static func png(width: Int, height: Int) throws -> Data {
        let context = try XCTUnwrap(CGContext(
            data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: 0,
            space: CGColorSpace(name: CGColorSpace.sRGB)!, bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue
        ))
        context.setFillColor(CGColor(red: 0.2, green: 0.4, blue: 0.9, alpha: 1))
        context.fill(CGRect(x: 0, y: 0, width: width, height: height))
        context.setFillColor(CGColor(red: 1, green: 0.5, blue: 0.2, alpha: 1))
        context.fillEllipse(in: CGRect(x: width / 4, y: height / 4, width: width / 2, height: height / 2))
        let image = try XCTUnwrap(context.makeImage())
        let rep = NSBitmapImageRep(cgImage: image)
        return try XCTUnwrap(rep.representation(using: .png, properties: [:]))
    }
}
